import { expect, test } from "@playwright/test"
import AxeBuilder from "@axe-core/playwright"

test("account registration, profile recovery, logout and sign-in work", async ({ page, context, browser }) => {
  const email = `account-browser-${Date.now()}-${test.info().project.name}@areve.test`
  const password = "Synthetic-browser-password-123"
  await page.goto("/ng/account")
  await page.getByRole("button", { name: "Join us", exact: true }).click()
  const register = page.getByTestId("register-page")
  await register.getByTestId("first-name-input").fill("Ada")
  await register.getByTestId("last-name-input").fill("Fixture")
  await register.getByTestId("email-input").fill(email)
  await register.getByTestId("password-input").fill(password)
  await expect(register.getByRole("link", { name: "Privacy Policy" })).toHaveAttribute("href", "/ng/privacy")
  await register.getByRole("button", { name: "Join", exact: true }).click()
  await expect(page.getByTestId("account-page")).toContainText("Ada")
  await expect(page.getByTestId("login-page")).not.toBeVisible()
  await page.goto("/ng/account/profile")
  await expect(page.getByTestId("account-password-editor")).toBeVisible()
  await expect(page.getByTestId("account-password-editor").getByRole("textbox", { name: "Email", exact: true })).toHaveValue(email)
  await expect(page.locator("main")).toHaveCount(1)
  const nameEditor = page.getByTestId("account-name-editor")
  await expect(nameEditor.getByRole("textbox", { name: "First name" })).not.toBeVisible()
  await nameEditor.getByRole("button", { name: "Edit name", exact: true }).click()
  await nameEditor.getByRole("textbox", { name: "First name", exact: true }).fill("Ada Updated")
  await nameEditor.getByRole("button", { name: "Save changes" }).click()
  await expect(nameEditor.getByRole("status")).toContainText("updated successfully")
  await expect(nameEditor.getByTestId("current-info")).toContainText("Ada Updated")
  await expect(nameEditor.getByRole("textbox", { name: "First name" })).not.toBeVisible()
  const accessibility = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()
  expect(accessibility.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => ({ target: n.target, html: n.html, summary: n.failureSummary })) }))).toEqual([])
  const billing = page.getByTestId("account-billing-address-editor")
  await billing.getByRole("button", { name: "Edit billing address", exact: true }).click()
  const fields = { "billing-first-name-input": "Ada", "billing-last-name-input": "Fixture", "billing-phone-input": "08000000000", "billing-address-1-input": "1 Synthetic Street", "billing-postcal-code-input": "100001", "billing-city-input": "Lagos", "billing-province-input": "Lagos" }
  for (const [id, value] of Object.entries(fields)) await billing.getByTestId(id).fill(value)
  await billing.getByRole("combobox", { name: "Country" }).selectOption("ng")
  const savedCookies = await context.cookies()
  await context.clearCookies({ name: "_medusa_jwt" })
  await billing.getByRole("button", { name: "Save changes" }).click()
  await expect(billing.getByRole("alert")).toBeVisible()
  await context.addCookies(savedCookies)
  for (const [id, value] of Object.entries(fields)) await billing.getByTestId(id).fill(value)
  await billing.getByRole("combobox", { name: "Country" }).selectOption("ng")
  await billing.getByRole("button", { name: "Save changes" }).click()
  await expect(billing.getByTestId("current-info")).toContainText("1 Synthetic Street")
  await page.goto("/ng/account/addresses")
  const address = page.getByTestId("address-container").filter({ hasText: "1 Synthetic Street" })
  await expect(address).toBeVisible()
  await context.clearCookies({ name: "_medusa_jwt" })
  await address.getByTestId("address-delete-button").click()
  await expect(address.getByRole("alert")).toContainText("Unable to remove")
  await expect(address.getByTestId("address-delete-button")).toBeEnabled()
  await context.addCookies(savedCookies)
  await address.getByTestId("address-delete-button").click()
  await expect(address).not.toBeVisible()
  const guest = await browser.newContext()
  try {
    const guestPage = await guest.newPage()
    await guestPage.goto("http://localhost:8000/ng/account")
    await expect(guestPage.getByTestId("login-page")).toBeVisible()
    await expect(guestPage.getByTestId("profile-link")).toHaveCount(0)
  } finally {
    await guest.close()
  }
  await page.goto("/ng/account")
  await page.getByTestId("logout-button").filter({ visible: true }).click()
  await expect(page.getByTestId("login-page")).toBeVisible()
  expect((await context.cookies()).some(cookie => cookie.name === "_medusa_jwt" && cookie.value)).toBe(false)
  await page.getByTestId("email-input").fill(email)
  await page.getByTestId("password-input").fill(password)
  await page.getByTestId("sign-in-button").click()
  await expect(page.getByTestId("login-page")).not.toBeVisible()
})

test("password recovery announces errors and does not send fragment credentials to the server", async ({ page }) => {
  await page.goto("/ng/account")
  await page.getByRole("link", { name: "Forgot your password?" }).click()
  await expect(page).toHaveURL(/\/ng\/forgot-password$/)
  await expect(page.getByRole("heading", { name: "Reset your password" })).toBeVisible()
  await page.getByRole("textbox", { name: "Email", exact: true }).fill(`unknown-${Date.now()}@areve.test`)
  await page.getByRole("button", { name: "Send reset link" }).click()
  await expect(page.getByRole("status")).toContainText("If an account exists")
  const requested: string[] = []
  page.on("request", request => requested.push(request.url()))
  await page.goto("/ng/reset-password#token=invalid-synthetic-fixture")
  await expect(page.getByLabel(/^New password/)).toBeVisible()
  await expect(page).toHaveURL(/\/ng\/reset-password$/)
  expect(requested.every(url => !url.includes("invalid-synthetic-fixture"))).toBe(true)
  await page.getByLabel(/^New password/).fill("Synthetic-new-password-123")
  await page.getByLabel(/^Confirm password/).fill("Synthetic-new-password-123")
  await page.getByRole("button", { name: "Update password" }).click()
  await expect(page.locator("main").getByRole("alert")).toContainText("could not be verified")
  const accessibility = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()
  expect(accessibility.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => ({ target: n.target, html: n.html, summary: n.failureSummary })) }))).toEqual([])
})
